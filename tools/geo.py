"""
Shared geography for the 3D map: projection, extent, relief, rivers, routes, anchors.
Map coordinates: X east, Y north (Blender: Z up;  three.js: (x, height, -y)).
1 world unit = 10 km horizontally.
"""
import math

# ---------------------------------------------------------------- projection (Lambert conformal conic)
R = 637.1                      # earth radius in world units (10 km)
PHI1, PHI2, PHI0, LAM0 = math.radians(20), math.radians(45), math.radians(30), 100.0

_n = math.log(math.cos(PHI1) / math.cos(PHI2)) / math.log(math.tan(math.pi / 4 + PHI2 / 2) / math.tan(math.pi / 4 + PHI1 / 2))
_F = math.cos(PHI1) * math.tan(math.pi / 4 + PHI1 / 2) ** _n / _n
_rho0 = R * _F / math.tan(math.pi / 4 + PHI0 / 2) ** _n


def project(lon, lat):
    if lon < LAM0 - 180:
        lon += 360
    phi = math.radians(lat)
    rho = R * _F / math.tan(math.pi / 4 + phi / 2) ** _n
    th = _n * math.radians(lon - LAM0)
    return rho * math.sin(th), _rho0 - rho * math.cos(th)


def unproject(x, y):
    rho = math.copysign(math.hypot(x, _rho0 - y), _n)
    th = math.atan2(x, _rho0 - y)
    phi = 2 * math.atan((R * _F / rho) ** (1 / _n)) - math.pi / 2
    return LAM0 + math.degrees(th / _n), math.degrees(phi)


